"""Offline tests that generate_hyperframes_project emits correct markup for zoom
and matte layering, WITHOUT invoking the HyperFrames CLI or any rendering."""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

import pytest                                            # noqa: E402
from podcut.models import Transcript, Word, ZoomEvent      # noqa: E402
from podcut import integrations                            # noqa: E402

SAMPLE_VIDEO = os.path.abspath(os.path.join(
    os.path.dirname(__file__), "..", "..", "real_sample", "cam1.mp4"))

pytestmark = pytest.mark.skipif(not os.path.exists(SAMPLE_VIDEO),
                                reason="needs real_sample/cam1.mp4 (generated by realsample.py)")


def _transcript():
    return Transcript(words=[Word(0.0, 0.5, "Hello", "A"), Word(0.6, 1.0, "world.", "A")])


def test_project_without_zoom_or_matte_has_no_zoom_wrap_scale_and_no_matte_video(tmp_path):
    proj = integrations.generate_hyperframes_project(SAMPLE_VIDEO, _transcript(), str(tmp_path))
    html = open(os.path.join(proj, "index.html"), encoding="utf-8").read()
    assert "ZOOM = []" in html
    assert 'data-track-index="2"' not in html          # no matte layer


def test_project_with_zoom_events_embeds_them_and_targets_main_video(tmp_path):
    events = [ZoomEvent(start=1.0, peak=1.2, release=1.8, end=2.2, scale=1.1, reason="punchline")]
    proj = integrations.generate_hyperframes_project(SAMPLE_VIDEO, _transcript(), str(tmp_path),
                                                     zoom_events=events)
    html = open(os.path.join(proj, "index.html"), encoding="utf-8").read()
    assert '"scale":1.1' in html.replace(" ", "")
    assert 'id="main-video"' in html
    assert 'getElementById("main-video")' in html


def test_project_with_matte_adds_top_layer_video_above_captions(tmp_path):
    matte_src = tmp_path / "fake_matte.webm"
    matte_src.write_bytes(b"not a real webm, just needs to exist")
    proj = integrations.generate_hyperframes_project(SAMPLE_VIDEO, _transcript(), str(tmp_path / "proj"),
                                                     matte=str(matte_src))
    html = open(os.path.join(proj, "index.html"), encoding="utf-8").read()
    assert 'data-track-index="2"' in html              # matte is the top track
    assert "media/matte.webm" in html
    assert os.path.exists(os.path.join(proj, "media", "matte.webm"))
    # matte must come AFTER the caption sub-composition in DOM order (paints on
    # top) and must NOT be nested inside any shared z-indexed wrapper with the
    # main video (a stacking-context trap that silently defeats this ordering).
    assert html.index("caption-highlight.html") < html.index("media/matte.webm")
    assert 'id="zoom-wrap"' not in html
    assert 'getElementById("matte-video")' in html


def test_project_with_lower_thirds_embeds_escaped_plates_and_tweens(tmp_path):
    lts = [{"time": 0.2, "name": 'Alice <&> "Q"'}, {"time": 2.2, "name": "Bob"}]
    proj = integrations.generate_hyperframes_project(SAMPLE_VIDEO, _transcript(), str(tmp_path),
                                                     lower_thirds=lts)
    html = open(os.path.join(proj, "index.html"), encoding="utf-8").read()
    assert 'id="lt-0"' in html and 'id="lt-1"' in html
    assert "Alice &lt;&amp;&gt; &quot;Q&quot;" in html   # names are HTML-escaped
    assert "LTS = " in html and '"time":' in html.replace(" ", "")
    # plates come after the caption overlay in DOM order (paint on top)
    assert html.index("caption-highlight.html") < html.index('id="lt-0"')


def test_project_without_lower_thirds_has_no_plate_markup(tmp_path):
    proj = integrations.generate_hyperframes_project(SAMPLE_VIDEO, _transcript(), str(tmp_path))
    html = open(os.path.join(proj, "index.html"), encoding="utf-8").read()
    assert 'class="lt"' not in html
    assert "LTS = []" in html
