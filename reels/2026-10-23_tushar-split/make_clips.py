"""Generate clips.json keep ranges from word timings: drop count-ins/bloopers, cut pauses > 0.3 s."""
import json
START = {1: 1.94, 2: 1.36, 3: 1.30, 4: 1.30, 5: 6.94, 6: 2.56, 7: 1.30}   # first kept word
DROP = {(4, "uh,")}
GAP, PAD_IN, PAD_OUT = 0.30, 0.06, 0.10
clips = []
for i in range(1, 8):
    w = [x for x in json.load(open(f"work/p{i}.transcript.json"))["words"]
         if x["start"] >= START[i] - 0.01 and (i, x["text"]) not in DROP]
    runs = [[w[0]["start"], w[0]["end"]]]
    for x in w[1:]:
        if x["start"] - runs[-1][1] > GAP:
            runs.append([x["start"], x["end"]])
        else:
            runs[-1][1] = x["end"]
    for a, b in runs:
        clips.append({"name": f"p{i}", "ext": ".mov", "keep": [round(a - PAD_IN, 2), round(b + PAD_OUT, 2)]})
tot = sum(c["keep"][1] - c["keep"][0] for c in clips)
json.dump({"_comment": "Tushar Chopra (RMA, MARN 2418420) -- 189 round 15 Oct 2026 occupation breakdown. 7 iPhone 4K60 HLG portrait takes P1-P7 from Tushar's Drive. Generated by make_clips.py (count-ins, p5 blooper and pauses > 0.3 s cut).",
           "clips": clips}, open("clips.json", "w"), indent=1)
print(len(clips), "segments", round(tot, 2), "s")
