"""Resolve which reel folder the pipeline scripts operate on.

Layout: every reel lives in its own folder under reels/, named
<YYYY-MM-DD>_<slug> (date of the event/publication), each containing
input/ (raw clips), work/ (intermediates), output/ (final mp4 + caption.txt).
The pipeline scripts stay shared at reels/ and act on ONE reel at a time:

  - set PODCUT_REEL to a folder name (or absolute path) to pick a reel, or
  - leave it unset to use the newest reel (date-prefixed names sort
    chronologically, so lexicographically-last == newest).

Pass --preview (or set PODCUT_PREVIEW=1) to any stage script, or to
build_all.py, for a fast draft build: lower render quality, isolated
work_preview/ intermediates (never collides with a full build's work/), and
several expensive steps skipped entirely -- see build_all.py and each
stage's own docstring for specifics. Never a deliverable (see qa_reel.py).

Shared brand assets (logo, end cards, music) are NOT per-reel; they stay in
podcut/assets.
"""
import os
import sys

# Content (badge/hero/thumbnail text, etc.) can legitimately contain emoji or
# other non-ASCII characters -- Windows' default console codepage (cp1252)
# can't encode those and crashes any print() that hits one. Every pipeline
# script imports this module, so fixing stdout/stderr encoding once here
# covers all of them. Guarded: reconfigure() isn't available on every stream
# (e.g. some CI/redirect setups), so a failure here should never itself take
# down the build over a cosmetic console-encoding concern.
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

REELS_ROOT = os.path.dirname(os.path.abspath(__file__))
PODCUT_ROOT = os.path.dirname(REELS_ROOT)
ASSETS_ROOT = os.path.join(PODCUT_ROOT, "assets")


def _is_reel(name: str) -> bool:
    return os.path.isdir(os.path.join(REELS_ROOT, name, "input"))


def reel_dir() -> str:
    env = os.environ.get("PODCUT_REEL")
    if env:
        p = env if os.path.isabs(env) else os.path.join(REELS_ROOT, env)
        if not os.path.isdir(p):
            raise SystemExit(f"PODCUT_REEL points at a missing folder: {p}")
        return p
    reels = sorted(d for d in os.listdir(REELS_ROOT) if _is_reel(d))
    if not reels:
        raise SystemExit("no reel folders under reels/ (expected <date>_<slug>/input/)")
    picked = os.path.join(REELS_ROOT, reels[-1])
    print(f"[reel] {os.path.basename(picked)} (set PODCUT_REEL to override)")
    return picked


# --preview (or PODCUT_PREVIEW=1) is checked here, not per-script, so every
# stage that already does `from reel_paths import WORK, ...` gets isolated
# preview/full intermediates for free -- same idea as real_sample's parallel
# work_ant/ work_heu/ work_stt/ directories, just keyed off this one flag
# instead of a fixed suffix. A preview build's segments/renders/mixes never
# collide with (or get overwritten by) a full build's, and vice versa.
PREVIEW = "--preview" in sys.argv or os.environ.get("PODCUT_PREVIEW") == "1"
# HyperFrames render quality: preview_window.py already trades quality for
# speed this same way ("-q draft" vs "-q standard") for fast iteration -- reuse
# that exact convention here instead of inventing a new speed/quality knob.
HF_QUALITY = "draft" if PREVIEW else "standard"
# The quality flag alone barely moves render time for these compositions --
# measured: a captions render at -q draft took ~118s, same as -q standard.
# Capture is bottlenecked by frame COUNT (one Chrome screenshot per frame),
# not per-frame quality, so preview mode also halves the capture framerate --
# ffmpeg's overlay filter reconciles the mismatch against the 30fps footage
# fine (it re-samples the overlay to the output's frame timing).
HF_FPS = 15 if PREVIEW else 30
# x264 preset: "medium" (the full-build default everywhere) trades encode
# speed for compression efficiency/quality-per-bit -- irrelevant for a draft
# that's thrown away, and this pipeline re-encodes at several stages (each
# clip segment, the B-roll splice, the wipe overlay, the captions composite,
# the final mix), so a faster preset compounds across all of them.
X264_PRESET = "ultrafast" if PREVIEW else "medium"

REEL = reel_dir()
IN = os.path.join(REEL, "input")
WORK = os.path.join(REEL, "work_preview" if PREVIEW else "work")
OUT = os.path.join(REEL, "output")
os.makedirs(WORK, exist_ok=True)
os.makedirs(OUT, exist_ok=True)

if PREVIEW:
    # Per-clip *.transcript.json files (build_base.py's load_clips()) come from
    # an external transcription step, not from anything in reels/*.py -- they
    # aren't regenerated by this pipeline, so full work_preview/ isolation would
    # otherwise strand a required input. Copy them forward from the full
    # work/ dir (read-only reuse; never written back) if not already present.
    # assembled.transcript.json is excluded -- that one IS pipeline-generated
    # (by build_base.py itself) and must be rebuilt fresh per mode.
    _full_work = os.path.join(REEL, "work")
    if os.path.isdir(_full_work):
        import shutil as _shutil
        for _fn in os.listdir(_full_work):
            if _fn.endswith(".transcript.json") and _fn != "assembled.transcript.json":
                _dst = os.path.join(WORK, _fn)
                if not os.path.isfile(_dst):
                    _shutil.copy2(os.path.join(_full_work, _fn), _dst)


def hyperframes_cli() -> str:
    """Resolve the HyperFrames CLI script (dist/cli.js) so every reel script
    works on any machine that has this repo checked out -- not just the one
    HYPERFRAMES_PATH (engine/.env) happened to be set up on.

    HYPERFRAMES_PATH is a per-machine dev setting; it can go stale (point at a
    checkout that only ever existed on whoever's machine set it up). Prefer it
    if it actually resolves, otherwise fall back to the copy vendored in this
    repo under tools/hyperframes -- that one travels with the repo."""
    sys.path.insert(0, os.path.join(PODCUT_ROOT, "engine"))
    from podcut.config import Providers  # noqa: E402

    configured = Providers().hyperframes_path
    if configured and os.path.isfile(os.path.join(configured, "dist", "cli.js")):
        return os.path.join(configured, "dist", "cli.js")

    vendored = os.path.join(PODCUT_ROOT, "tools", "hyperframes", "node_modules", "hyperframes")
    if os.path.isfile(os.path.join(vendored, "dist", "cli.js")):
        return os.path.join(vendored, "dist", "cli.js")

    raise SystemExit(
        "Can't find the HyperFrames CLI (checked HYPERFRAMES_PATH and "
        "podcut/tools/hyperframes/node_modules/hyperframes) -- set "
        "HYPERFRAMES_PATH or `npm install` under tools/hyperframes.")
